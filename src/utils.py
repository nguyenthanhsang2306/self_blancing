import os
import random
import numpy as np
import matplotlib.pyplot as plt

def set_seed(seed=42):
    """Cố định seed ngẫu nhiên cho tính tái lập (Reproducibility)."""
    random.seed(seed)
    np.random.seed(seed)
    try:
        import torch
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(seed)
    except ImportError:
        pass

def export_sb3_c_header(policy, output_path):
    """
    Bước 6: Xuất toàn bộ ma trận trọng số và hàm suy luận siêu tốc C
    sang file header không phụ thuộc (zero-dependency) để nhúng vào STM32L476RG.
    """
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    w1, b1 = policy.w1, policy.b1
    w2, b2 = policy.w2, policy.b2
    w3, b3 = policy.w3, policy.b3

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("/**\n")
        f.write(" * ============================================================================\n")
        f.write(" * AUTOGENERATED REINFORCEMENT LEARNING CONTROLLER FOR STM32L476RG\n")
        f.write(" * Model Architecture: MLP [4 -> 64 -> 64 -> 1] (Trained via PPO / SB3)\n")
        f.write(" * Latency: ~25-50 microseconds @ 80 MHz Cortex-M4 with FPU\n")
        f.write(" * ============================================================================\n")
        f.write(" */\n\n")
        f.write("#ifndef RL_SB3_STM32_H\n")
        f.write("#define RL_SB3_STM32_H\n\n")
        f.write("#include <math.h>\n\n")

        # Layer 1 weights (64, 4)
        f.write("/* --- Layer 1: Input (4) -> Hidden 1 (64) --- */\n")
        f.write("static const float RL_W1[64][4] = {\n")
        for i in range(64):
            row_str = ", ".join([f"{w1[i, j]:.7f}f" for j in range(4)])
            f.write(f"    {{ {row_str} }},\n")
        f.write("};\n\n")

        f.write("static const float RL_B1[64] = {\n    ")
        f.write(", ".join([f"{b1[i]:.7f}f" for i in range(64)]))
        f.write("\n};\n\n")

        # Layer 2 weights (64, 64)
        f.write("/* --- Layer 2: Hidden 1 (64) -> Hidden 2 (64) --- */\n")
        f.write("static const float RL_W2[64][64] = {\n")
        for i in range(64):
            row_str = ", ".join([f"{w2[i, j]:.7f}f" for j in range(64)])
            f.write(f"    {{ {row_str} }},\n")
        f.write("};\n\n")

        f.write("static const float RL_B2[64] = {\n    ")
        f.write(", ".join([f"{b2[i]:.7f}f" for i in range(64)]))
        f.write("\n};\n\n")

        # Layer 3 weights (1, 64)
        f.write("/* --- Layer 3: Hidden 2 (64) -> Output Action (1) --- */\n")
        f.write("static const float RL_W3[64] = {\n    ")
        f.write(", ".join([f"{w3[0, j]:.7f}f" for j in range(64)]))
        f.write("\n};\n\n")
        f.write(f"static const float RL_B3 = {b3[0]:.7f}f;\n\n")

        # Inference function
        f.write("/**\n")
        f.write(" * @brief Hàm suy luận thời gian thực cho chu kỳ 200 Hz (5 ms)\n")
        f.write(" * @param theta  Góc nghiêng (rad)\n")
        f.write(" * @param dtheta Vận tốc góc (rad/s)\n")
        f.write(" * @param x      Vị trí (m)\n")
        f.write(" * @param v      Vận tốc di chuyển (m/s)\n")
        f.write(" * @return float Xung PWM điều khiển động cơ [-999.0, +999.0]\n")
        f.write(" */\n")
        f.write("static inline float RL_SB3_Inference(float theta, float dtheta, float x, float v) {\n")
        f.write("    float in_vec[4] = { theta, dtheta, x, v };\n")
        f.write("    float h1[64];\n\n")
        f.write("    /* Tầng ẩn 1: Linear + ReLU */\n")
        f.write("    for (int i = 0; i < 64; i++) {\n")
        f.write("        float sum = RL_B1[i];\n")
        f.write("        for (int j = 0; j < 4; j++) {\n")
        f.write("            sum += RL_W1[i][j] * in_vec[j];\n")
        f.write("        }\n")
        f.write("        h1[i] = (sum > 0.0f) ? sum : 0.0f;\n")
        f.write("    }\n\n")
        f.write("    /* Tầng ẩn 2: Linear + ReLU */\n")
        f.write("    float h2[64];\n")
        f.write("    for (int i = 0; i < 64; i++) {\n")
        f.write("        float sum = RL_B2[i];\n")
        f.write("        for (int j = 0; j < 64; j++) {\n")
        f.write("            sum += RL_W2[i][j] * h1[j];\n")
        f.write("        }\n")
        f.write("        h2[i] = (sum > 0.0f) ? sum : 0.0f;\n")
        f.write("    }\n\n")
        f.write("    /* Tầng đầu ra: Linear + Tanh bão hòa */\n")
        f.write("    float out = RL_B3;\n")
        f.write("    for (int j = 0; j < 64; j++) {\n")
        f.write("        out += RL_W3[j] * h2[j];\n")
        f.write("    }\n\n")
        f.write("    /* Hàm Tanh giới hạn hành động mượt mà trong [-1, 1] và nhân với PWM_MAX */\n")
        f.write("    float action = tanhf(out);\n")
        f.write("    float pwm = action * 999.0f;\n")
        f.write("    if (pwm > 999.0f) pwm = 999.0f;\n")
        f.write("    if (pwm < -999.0f) pwm = -999.0f;\n")
        f.write("    return pwm;\n")
        f.write("}\n\n")
        f.write("#endif /* RL_SB3_STM32_H */\n")

    print(f"[Export] Đã xuất thành công C Header sang: {output_path}")

def plot_simulation_trajectory(t_arr, theta_arr, x_arr, pwm_arr, output_path):
    """Vẽ đồ thị phản hồi cân bằng và chống rung."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    fig, (ax1, ax2, ax3) = plt.subplots(3, 1, figsize=(10, 8), sharex=True)

    ax1.plot(t_arr, theta_arr, 'b-', label='Pitch Angle (deg)', linewidth=1.8)
    ax1.axhline(0, color='k', linestyle='--', alpha=0.6)
    ax1.set_ylabel("Angle (deg)")
    ax1.grid(True, alpha=0.3)
    ax1.legend(loc='upper right')
    ax1.set_title("Self-Balancing Robot: Reinforcement Learning (PPO SB3) Response", fontsize=12, fontweight='bold')

    ax2.plot(t_arr, x_arr, 'g-', label='Position x (m)', linewidth=1.8)
    ax2.axhline(0, color='k', linestyle='--', alpha=0.6)
    ax2.set_ylabel("Position (m)")
    ax2.grid(True, alpha=0.3)
    ax2.legend(loc='upper right')

    ax3.plot(t_arr, pwm_arr, 'r-', label='Motor Action (PWM)', linewidth=1.2)
    ax3.axhline(0, color='k', linestyle='--', alpha=0.6)
    ax3.set_ylabel("PWM Output")
    ax3.set_xlabel("Time (seconds)")
    ax3.grid(True, alpha=0.3)
    ax3.legend(loc='upper right')

    plt.tight_layout()
    plt.savefig(output_path, dpi=200)
    plt.close()
    print(f"[Plot] Đã lưu đồ thị mô phỏng sang: {output_path}")
